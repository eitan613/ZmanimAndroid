import java.awt.Font;
import java.awt.Shape;
import java.awt.font.FontRenderContext;
import java.awt.geom.AffineTransform;
import java.awt.geom.PathIterator;
import java.awt.geom.Rectangle2D;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;

/** Run with java tools/GenerateHebrewDayIcons.java [path/to/DejaVuSans-Bold.ttf]. */
class GenerateHebrewDayIcons {
    public static void main(String[] args) throws Exception {
        var fontPath = Path.of(args.length == 0 ? "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" : args[0]);
        var font = Font.createFont(Font.TRUETYPE_FONT, fontPath.toFile()).deriveFont(24f);
        var context = new FontRenderContext(null, true, true);
        String[] days = {"א", "ב", "ג", "ד", "ה", "ו", "ז", "ח", "ט", "י", "יא", "יב", "יג", "יד", "טו", "טז", "יז", "יח", "יט", "כ", "כא", "כב", "כג", "כד", "כה", "כו", "כז", "כח", "כט", "ל"};
        for (int day = 1; day <= 30; day++) {
            char[] letters = days[day - 1].toCharArray();
            Shape outline = font.layoutGlyphVector(context, letters, 0, letters.length, Font.LAYOUT_RIGHT_TO_LEFT).getOutline();
            Rectangle2D bounds = outline.getBounds2D();
            double scale = Math.min(20 / bounds.getWidth(), 18 / bounds.getHeight());
            var transform = new AffineTransform();
            transform.translate((24 - bounds.getWidth() * scale) / 2, (24 - bounds.getHeight() * scale) / 2);
            transform.scale(scale, scale);
            transform.translate(-bounds.getX(), -bounds.getY());
            var iterator = outline.getPathIterator(transform);
            var path = new StringBuilder();
            double[] c = new double[6];
            while (!iterator.isDone()) {
                int type = iterator.currentSegment(c);
                path.append(switch(type) { case 0 -> "M"; case 1 -> "L"; case 2 -> "Q"; case 3 -> "C"; default -> "Z"; });
                int count = switch(type) { case 0, 1 -> 2; case 2 -> 4; case 3 -> 6; default -> 0; };
                for (int i = 0; i < count; i++) path.append(String.format(Locale.ROOT, "%s%.3f", i == 0 ? "" : ",", c[i]));
                iterator.next();
            }
            Files.writeString(Path.of("app/src/main/res/drawable/hebrew_day_" + day + ".xml"),
                "<!-- Hebrew day " + day + ": " + days[day - 1] + "; generated by tools/GenerateHebrewDayIcons.java. -->\n" +
                "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\" android:width=\"24dp\" android:height=\"24dp\" android:viewportWidth=\"24\" android:viewportHeight=\"24\"><path android:fillColor=\"#FFFFFFFF\" android:pathData=\"" + path + "\" /></vector>\n");
        }
    }
}
